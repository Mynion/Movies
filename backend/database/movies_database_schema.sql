BEGIN;

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    role VARCHAR(20) NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'admin')),
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE media_items (
    media_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    duration INTEGER CHECK (duration IS NULL OR duration >= 0),
    media_type VARCHAR(20) NOT NULL
        CHECK (media_type IN ('movie', 'tv_series', 'season', 'episode')),
    parent_id BIGINT,
    season_number INTEGER CHECK (season_number IS NULL OR season_number >= 1),
    episode_number INTEGER CHECK (episode_number IS NULL OR episode_number >= 1),
    poster_path TEXT,
    tmdb_id BIGINT,
    release_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_media_items_parent
        FOREIGN KEY (parent_id) REFERENCES media_items(media_item_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_media_items_not_own_parent
        CHECK (parent_id IS NULL OR parent_id <> media_item_id)
);

CREATE TABLE genre (
    genre_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200),
    content TEXT NOT NULL,
    visibility VARCHAR(20) NOT NULL DEFAULT 'public'
        CHECK (visibility IN ('public', 'private')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fk1_user_id BIGINT NOT NULL,
    fk2_media_item_id BIGINT NOT NULL,
    CONSTRAINT fk_reviews_user
        FOREIGN KEY (fk1_user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_reviews_media_item
        FOREIGN KEY (fk2_media_item_id) REFERENCES media_items(media_item_id) ON DELETE RESTRICT
);

CREATE TABLE lists (
    list_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visibility VARCHAR(20) NOT NULL DEFAULT 'private'
        CHECK (visibility IN ('public', 'private')),
    name VARCHAR(100) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fk1_user_id BIGINT NOT NULL,
    CONSTRAINT fk_lists_user
        FOREIGN KEY (fk1_user_id) REFERENCES users(user_id) ON DELETE RESTRICT
);

CREATE TABLE ratings (
    rating_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    value NUMERIC(3,1) NOT NULL CHECK (value BETWEEN 1 AND 10),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fk1_user_id BIGINT NOT NULL,
    fk2_media_item_id BIGINT NOT NULL,
    CONSTRAINT fk_ratings_user
        FOREIGN KEY (fk1_user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_ratings_media_item
        FOREIGN KEY (fk2_media_item_id) REFERENCES media_items(media_item_id) ON DELETE RESTRICT,
    CONSTRAINT uq_ratings_user_media_item UNIQUE (fk1_user_id, fk2_media_item_id)
);

CREATE TABLE watch_history (
    watch_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    watched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    progress INTEGER CHECK (progress IS NULL OR progress BETWEEN 0 AND 100),
    fk1_user_id BIGINT NOT NULL,
    media_item_id BIGINT NOT NULL,
    CONSTRAINT fk_watch_history_user
        FOREIGN KEY (fk1_user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_watch_history_media_item
        FOREIGN KEY (media_item_id) REFERENCES media_items(media_item_id) ON DELETE RESTRICT
);

CREATE TABLE comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fk1_user_id BIGINT NOT NULL,
    fk2_review_id BIGINT NOT NULL,
    CONSTRAINT fk_comments_user
        FOREIGN KEY (fk1_user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_comments_review
        FOREIGN KEY (fk2_review_id) REFERENCES reviews(review_id) ON DELETE CASCADE
);

CREATE TABLE report (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fk1_user_id BIGINT NOT NULL,
    fk2_comment_id BIGINT NOT NULL,
    CONSTRAINT fk_report_user
        FOREIGN KEY (fk1_user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_report_comment
        FOREIGN KEY (fk2_comment_id) REFERENCES comments(comment_id) ON DELETE CASCADE
);

CREATE TABLE review_likes (
    review_like_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fk1_review_id BIGINT NOT NULL,
    fk2_user_id BIGINT NOT NULL,
    CONSTRAINT fk_review_likes_review
        FOREIGN KEY (fk1_review_id) REFERENCES reviews(review_id) ON DELETE CASCADE,
    CONSTRAINT fk_review_likes_user
        FOREIGN KEY (fk2_user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT uq_review_likes_review_user UNIQUE (fk1_review_id, fk2_user_id)
);

CREATE TABLE user_genre_preferences (
    user_genre_preference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    preference_score INTEGER CHECK (preference_score IS NULL OR preference_score BETWEEN 1 AND 10),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fk1_user_id BIGINT NOT NULL,
    fk2_genre_id BIGINT NOT NULL,
    CONSTRAINT fk_user_genre_preferences_user
        FOREIGN KEY (fk1_user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_genre_preferences_genre
        FOREIGN KEY (fk2_genre_id) REFERENCES genre(genre_id) ON DELETE CASCADE,
    CONSTRAINT uq_user_genre_preferences_user_genre UNIQUE (fk1_user_id, fk2_genre_id)
);

CREATE TABLE media_item_statistics (
    media_item_statistic_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avg_rating NUMERIC(4,2) CHECK (avg_rating IS NULL OR avg_rating BETWEEN 1 AND 10),
    total_ratings INTEGER NOT NULL DEFAULT 0 CHECK (total_ratings >= 0),
    total_reviews INTEGER NOT NULL DEFAULT 0 CHECK (total_reviews >= 0),
    watch_count INTEGER NOT NULL DEFAULT 0 CHECK (watch_count >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fk1_media_item_id BIGINT NOT NULL UNIQUE,
    CONSTRAINT fk_media_item_statistics_media_item
        FOREIGN KEY (fk1_media_item_id) REFERENCES media_items(media_item_id) ON DELETE CASCADE
);

CREATE TABLE rating_score (
    rating_score_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score_type VARCHAR(30) NOT NULL
        CHECK (score_type IN ('story_score', 'acting_score', 'soundtrack_score', 'overall_score', 'custom_score')),
    score NUMERIC(3,1) NOT NULL CHECK (score BETWEEN 1 AND 10),
    to_average BOOLEAN NOT NULL DEFAULT TRUE,
    custom_name VARCHAR(100),
    fk1_rating_id BIGINT NOT NULL,
    CONSTRAINT fk_rating_score_rating
        FOREIGN KEY (fk1_rating_id) REFERENCES ratings(rating_id) ON DELETE CASCADE,
    CONSTRAINT chk_rating_score_custom_name
        CHECK (
            (score_type = 'custom_score' AND custom_name IS NOT NULL AND length(trim(custom_name)) > 0)
            OR
            (score_type <> 'custom_score' AND custom_name IS NULL)
        )
);

CREATE TABLE lists_media_items (
    s_list_id BIGINT NOT NULL,
    d_media_item_id BIGINT NOT NULL,
    PRIMARY KEY (s_list_id, d_media_item_id),
    CONSTRAINT fk_lists_media_items_list
        FOREIGN KEY (s_list_id) REFERENCES lists(list_id) ON DELETE CASCADE,
    CONSTRAINT fk_lists_media_items_media_item
        FOREIGN KEY (d_media_item_id) REFERENCES media_items(media_item_id) ON DELETE CASCADE
);

CREATE TABLE media_items_genre (
    s_media_item_id BIGINT NOT NULL,
    d_genre_id BIGINT NOT NULL,
    PRIMARY KEY (s_media_item_id, d_genre_id),
    CONSTRAINT fk_media_items_genre_media_item
        FOREIGN KEY (s_media_item_id) REFERENCES media_items(media_item_id) ON DELETE CASCADE,
    CONSTRAINT fk_media_items_genre_genre
        FOREIGN KEY (d_genre_id) REFERENCES genre(genre_id) ON DELETE CASCADE
);

CREATE INDEX idx_media_items_parent_id ON media_items(parent_id);
CREATE INDEX idx_reviews_user_id ON reviews(fk1_user_id);
CREATE INDEX idx_reviews_media_item_id ON reviews(fk2_media_item_id);
CREATE INDEX idx_lists_user_id ON lists(fk1_user_id);
CREATE INDEX idx_ratings_media_item_id ON ratings(fk2_media_item_id);
CREATE INDEX idx_watch_history_user_watched_at ON watch_history(fk1_user_id, watched_at DESC);
CREATE INDEX idx_watch_history_media_item_id ON watch_history(media_item_id);
CREATE INDEX idx_comments_review_id ON comments(fk2_review_id);
CREATE INDEX idx_report_comment_id ON report(fk2_comment_id);
CREATE INDEX idx_rating_score_rating_id ON rating_score(fk1_rating_id);

COMMIT;
